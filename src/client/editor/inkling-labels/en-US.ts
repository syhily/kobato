// English is NOT re-typed here: every built-in key reads Inkling's own
// `DEFAULT_LABELS` value (one source, no drift), while the host-card menu
// namespace (`menu.host.*`) has no Inkling default — its English text is the
// card menu entry's own copy, written out here.
//
// The table covers ONLY the keys Kobato actually mounts (156 keys: built-in
// chrome + the three host-card menu entries). Unmounted inkling features —
// gif.* / pintura.* / snippet.* and their menu/toolbar keys — deliberately stay
// absent and keep falling back to Inkling's English defaults.
//
// `satisfies InklingLabelsInput` proves every key is legal (closed table plus
// the host-menu namespace). `KobatoInklingLabelKey` is the key set the three
// other locales are held to.
//
// Interpolation tokens (`{max}` / `{cardType}` / `{name}` / `{progress}`) are
// the consumption-site `string.replace` contract — never translate them.

