import { sliceFont } from '@kobato/server/domains/fonts/slice'
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const TTF_PATH = join(import.meta.dirname, '../../../../fixtures/fonts/Barlow-Regular.ttf')

function tableRecordOffsets(source: Uint8Array, tag: string): number[] {
  const numTables = ((source[4] ?? 0) << 8) | (source[5] ?? 0)
  return Array.from({ length: numTables }, (_, i) => 12 + i * 16).filter(
    (record) => String.fromCharCode(...source.subarray(record, record + 4)) === tag,
  )
}

function withUnreadableCmap(source: Uint8Array): Uint8Array {
  const damaged = new Uint8Array(source)
  const view = new DataView(damaged.buffer)
  const [record] = tableRecordOffsets(damaged, 'cmap')
  if (record === undefined) {
    throw new Error('fixture has no cmap table')
  }
  view.setUint32(view.getUint32(record + 8) + 8, 0xffff_ff00)
  return damaged
}

describe('sliceFont', () => {
  it('slices a real TTF into a non-empty result.css + woff2 chunks', async () => {
    const source = await readFile(TTF_PATH)
    expect(source.length).toBeGreaterThan(0)

    const result = await sliceFont(source, { fontFamily: 'Barlow' })

    const cssText = Buffer.from(result.css).toString('utf8')
    expect(cssText).toContain('@font-face')
    expect(cssText).toMatch(/\.woff2['")]/)
    expect(cssText).toContain('Barlow')
    expect(cssText).not.toContain('CreateTime:')
    expect(cssText).not.toContain('Generated By')

    expect(result.chunkCount).toBeGreaterThan(0)
    expect(result.chunks.length).toBe(result.chunkCount)
    for (const chunk of result.chunks) {
      expect(chunk.name).toMatch(/\.woff2$/)
      expect(chunk.data[0]).toBe(0x77)
      expect(chunk.data[1]).toBe(0x4f)
      expect(chunk.data[2]).toBe(0x46)
      expect(chunk.data.length).toBeGreaterThan(0)
    }

    const expectedTotal = result.css.length + result.chunks.reduce((n, c) => n + c.data.length, 0)
    expect(result.totalBytes).toBe(expectedTotal)
  }, 60_000)

  it('produces the same package every time for the same font', async () => {
    const source = await readFile(TTF_PATH)

    const first = await sliceFont(source, { fontFamily: 'Barlow' })
    const second = await sliceFont(source, { fontFamily: 'Barlow' })

    expect(Buffer.from(second.css).equals(Buffer.from(first.css))).toBe(true)
    expect(second.chunks.map((chunk) => [chunk.name, chunk.data.length])).toEqual(
      first.chunks.map((chunk) => [chunk.name, chunk.data.length]),
    )
  }, 60_000)

  it('rejects a font whose table directory is intact but whose cmap cannot be read', async () => {
    const source = withUnreadableCmap(await readFile(TTF_PATH))

    await expect(sliceFont(source, { fontFamily: 'Barlow' })).rejects.toMatchObject({
      name: 'DomainError',
      code: 'BAD_REQUEST',
      descriptor: { messageKey: 'fonts.error.unreadable' },
    })
  }, 60_000)
})
