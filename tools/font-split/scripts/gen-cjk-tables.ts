// Regenerates src/lang_unicodes/cjk_tables.rs from the vendored character lists
// under scripts/cjk-tables/.
// Run from the package root: `pnpm run cjk-tables:generate` (Node 26 type stripping).
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const pkgRoot = join(import.meta.dirname, '..')
const tableDir = join(import.meta.dirname, 'cjk-tables')
const outFile = join(pkgRoot, 'src', 'lang_unicodes', 'cjk_tables.rs')

function readTable(file: string): string[] {
  const lines = readFileSync(join(tableDir, file), 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith('#'))
  // The TW less-common table marks chars removed by the 2017 正字表 revision with a
  // trailing ※ (5 待考正字 + 9 unit symbols); those stay out of the standard list.
  // HK/JA lines may carry a 〔variant〕/﹝variant﹞ annotation (e.g. 丟〔丢〕, 𠮟﹝叱﹞);
  // the standard form is the first code point.
  return lines.filter((line) => !line.endsWith('※')).map((line) => String.fromCodePoint(line.codePointAt(0)!))
}

function dedupe(chars: string[]): string[] {
  return [...new Set(chars)]
}

const tghL1 = dedupe(readTable('tgh-2013-level-1.txt'))
const tghL2 = dedupe(readTable('tgh-2013-level-2.txt'))
const tghL3 = dedupe(readTable('tgh-2013-level-3.txt'))
const tghAll = new Set([...tghL1, ...tghL2, ...tghL3])

// Regional supplements, deduplicated against everything already packed.
const zhHk = dedupe(readTable('hk-common-4762.txt')).filter((c) => !tghAll.has(c))
const zhHkSet = new Set(zhHk)
const zhTw = dedupe([...readTable('tw-common-4808.txt'), ...readTable('tw-less-common-6329.txt')]).filter(
  (c) => !tghAll.has(c) && !zhHkSet.has(c),
)
const zhTwSet = new Set(zhTw)
const zhJa = dedupe(readTable('ja-joyo-2136.txt')).filter((c) => !tghAll.has(c) && !zhHkSet.has(c) && !zhTwSet.has(c))

const hangulSyl = dedupe(readTable('ko-syllables-2026.txt'))

const expected: Array<[string, number, number]> = [
  ['ZH_TGH_L1', tghL1.length, 3500],
  ['ZH_TGH_L2', tghL2.length, 3000],
  ['ZH_TGH_L3', tghL3.length, 1605],
  ['ZH_JA raw', dedupe(readTable('ja-joyo-2136.txt')).length, 2136],
  ['ZH_TW less-common raw', readTable('tw-less-common-6329.txt').length, 6329],
  ['HANGUL_SYL', hangulSyl.length, 2026],
]
for (const [name, actual, want] of expected) {
  if (actual !== want) {
    throw new Error(`${name}: expected ${want} chars, got ${actual} — vendored source data drifted`)
  }
}

function renderConst(name: string, chars: string[]): string {
  return `pub(crate) const ${name}: &str = ${JSON.stringify(chars.join(''))};\n`
}

const rust = `//! @generated by \`pnpm run cjk-tables:generate\` — do not edit by hand.
//!
//! Chinese-character priority tables for subset packing, built from official
//! regional standards (see scripts/cjk-tables/ for the vendored sources):
//! - ZH_TGH_L1/L2/L3: 中国大陆《通用规范汉字表》(2013) 一/二/三级字表 (3500/3000/1605)
//! - ZH_HK: 香港《常用字字形表》 minus the mainland table (${zhHk.length} supplementary chars)
//! - ZH_TW: 臺灣《常用國字標準字體表》+《次常用國字標準字體表》 minus the mainland table and ZH_HK (${zhTw.length} supplementary chars)
//! - ZH_JA: 日本《常用漢字表》(2010) minus the mainland table, ZH_HK and ZH_TW (${zhJa.length} supplementary chars)
//! - HANGUL_SYL: 韩语高频音节表 (2026, 按语料频率降序)

${renderConst('ZH_TGH_L1', tghL1)}${renderConst('ZH_TGH_L2', tghL2)}${renderConst('ZH_TGH_L3', tghL3)}${renderConst('ZH_HK', zhHk)}${renderConst('ZH_TW', zhTw)}${renderConst('ZH_JA', zhJa)}${renderConst('HANGUL_SYL', hangulSyl)}`

writeFileSync(outFile, rust)
process.stdout.write(
  `wrote ${outFile}\n  ZH_TGH_L1=${tghL1.length} ZH_TGH_L2=${tghL2.length} ZH_TGH_L3=${tghL3.length}` +
    `\n  ZH_HK=${zhHk.length} ZH_TW=${zhTw.length} ZH_JA=${zhJa.length} HANGUL_SYL=${hangulSyl.length}\n`,
)
